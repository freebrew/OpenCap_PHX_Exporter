// Reads apps-script/entry_schema.js and writes src/families.gen.ts, so the phone, the API and the
// snapshot test all render the wizard from the generated schema rather than a hand copy.
import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";

const source = readFileSync(new URL("../../../strapsheets/apps-script/entry_schema.js", import.meta.url), "utf8");
const whichAt = source.indexOf("var ENTRY_WHICH_OPTIONS");
const json = source.slice(source.indexOf("["), whichAt).replace(/]\s*;\s*$/, "]");
const families = JSON.parse(json);
const whichJson = source.slice(source.indexOf("[", whichAt), source.indexOf("]", whichAt) + 1);
const whichOptions = JSON.parse(whichJson);
const customSource = readFileSync(new URL("../../../strapsheets/apps-script/custom_family.js", import.meta.url), "utf8");
const sandbox = { ENTRY_FAMILIES: families, ENTRY_WHICH_OPTIONS: whichOptions };
vm.runInNewContext(`${customSource}\nensureCustomFamily_();`, sandbox);
const out = `// GENERATED by scripts/gen-families.mjs from apps-script/entry_schema.js and custom_family.js. Do not edit.
import type { EntryFamily } from "./schema";

export const ENTRY_FAMILIES: EntryFamily[] = ${JSON.stringify(families, null, 2)};

/** Front-page order of the tool buttons. */
export const ENTRY_WHICH_OPTIONS: string[] = ${JSON.stringify(whichOptions, null, 2)};
`;
writeFileSync(new URL("../src/families.gen.ts", import.meta.url), out);
console.log(`families: ${families.length}, steps: ${families.reduce((n, f) => n + f.steps.length, 0)}, front page: ${whichOptions.length}`);
for (const family of families) console.log(`  ${family.which}: ${family.steps.map((s) => s.kind).join(" ")}`);
