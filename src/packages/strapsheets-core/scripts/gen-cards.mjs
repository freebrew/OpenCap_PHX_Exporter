// Reads apps-script/print_config.js (the card cells the Sheets print engine stamps) and
// illustrations/vectors/drawlists.json (the tool drawings), then writes src/cards.gen.ts and
// src/art.gen.ts so the phone and the Worker draw the same card the Sheets printout shows.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { runInNewContext } from "node:vm";

const appsScript = new URL("../../../strapsheets/apps-script/", import.meta.url);

function load(file, ...names) {
  const scope = {};
  runInNewContext(`${readFileSync(new URL(file, appsScript), "utf8")}\n;this.out = { ${names.join(", ")} };`, scope);
  return scope.out;
}

// The MWD Carrier's card is added to PRINT_CONFIG by mwd_carrier.js, as the print sidebar does.
const printScope = {};
runInNewContext(
  `${readFileSync(new URL("print_config.js", appsScript), "utf8")}\n${readFileSync(new URL("mwd_carrier.js", appsScript), "utf8")}\nensureMwdPrint_();\nthis.out = { PRINT_CONFIG };`,
  printScope,
);
const { PRINT_CONFIG } = printScope.out;
const { ENTRY_DIAGRAMS } = load("entry_diagrams.js", "ENTRY_DIAGRAMS");
const drawlistPath = new URL("../../../strapsheets/illustrations/vectors/drawlists.json", import.meta.url);
const drawlistText = readFileSync(drawlistPath, "utf8");
const drawlists = JSON.parse(drawlistText);
const drawByWhich = new Map(drawlists.map((tool) => [tool.which, tool]));

// The entry family each print tab prints (print_cards.py WHICH), and the title the live tab
// carries under its cards (print_restyle_snapshot manifest footerLabel).
const TABS = {
  Motors: { which: "Motor", title: "MOTORS" },
  Orbits: { which: "Orbit", title: "ORBITS" },
  Floats: { which: "Subs", title: "FLOAT Subs" },
  GAPs: { which: "Subs", title: "GAP/PULSER SUBS" },
  FlexNMs: { which: "NM Flex Monel", title: "FLEX NM" },
  StabsNMCarriers: { which: "NM Stabilizer Carrier", title: "STAB NM CARRIER" },
  HMJs: { which: "Jars", title: "JARS" },
  SlickNMs: { which: "NM Slick Monel", title: "SLICK NM" },
  PonyNMs: { which: "NM Pony", title: "PONY NM" },
  "X-Overs": { which: "Subs", title: "X-Overs" },
  LiftingSubs: { which: "Lifting Subs", title: "LIFTING SUBS" },
  StabSub: { which: "Stabilized Sub", title: "Stub Subs" },
  ShockSubs: { which: "Shock Sub", title: "SHOCKSUBS" },
  Exciters: { which: "Exciter / Agitator / Sidewinder", title: "EXCITERS" },
  "MWD Carrier": { which: "MWD Carrier", title: "MWD" },
};

// Custom (source "custom") is drawn from its own payload; the other tabs, MWD included, are tables.
const cards = PRINT_CONFIG.filter((family) => !family.source || family.source === "mwd").map((family) => {
  const tab = TABS[family.name];
  if (!tab) throw new Error(`print_config.js has a tab with no entry family: ${family.name}`);
  if (!ENTRY_DIAGRAMS[tab.which]) throw new Error(`${tab.which}: no drawing in entry_diagrams.js`);
  return {
    name: family.name,
    which: tab.which,
    title: tab.title,
    width: family.width,
    positions: family.positions,
    posShift: family.posShift,
    rowHeights: family.rowHeights,
    serialCell: family.serialCell,
    typeCol: family.typeCol,
    typeValues: family.typeValues,
    statics: family.statics,
    fields: family.fields,
    ...(family.headerSpans ? { headerSpans: family.headerSpans } : {}),
    ...(family.metricFrom != null ? { metricFrom: family.metricFrom } : {}),
  };
});
for (const name of Object.keys(TABS)) {
  if (!cards.some((card) => card.name === name)) throw new Error(`${name} is missing from print_config.js`);
}

const art = {};
for (const tab of Object.values(TABS)) {
  const tool = drawByWhich.get(tab.which);
  if (!tool) throw new Error(`${tab.which}: no vector drawing`);
  if (!ENTRY_DIAGRAMS[tab.which]) throw new Error(`${tab.which}: no sheet bitmap`);
  art[tab.which] = { kind: "vector", w: tool.w, h: tool.h, items: tool.items };
}

writeFileSync(
  new URL("../src/cards.gen.ts", import.meta.url),
  `// GENERATED by scripts/gen-cards.mjs from apps-script/print_config.js. Do not edit.
import type { PrintCard } from "./cardSpec";

export const PRINT_CARDS: PrintCard[] = ${JSON.stringify(cards, null, 2)};
`,
);
writeFileSync(
  new URL("../src/art.gen.ts", import.meta.url),
  `// GENERATED by scripts/gen-cards.mjs from illustrations/vectors/drawlists.json. Do not edit.
// source ${createHash("sha256").update(drawlistText).digest("hex").slice(0, 16)}
import type { CardArt } from "./cardSpec";

export const CARD_ART: Record<string, CardArt> = ${JSON.stringify(art, null, 2)};
`,
);
console.log(`cards: ${cards.length}, drawings: ${Object.keys(art).length}`);
for (const card of cards) console.log(`  ${card.name} -> ${card.which} "${card.title}" ${card.width} cols x${card.positions}`);
