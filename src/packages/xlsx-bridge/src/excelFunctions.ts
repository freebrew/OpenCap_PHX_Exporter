export const EXCEL_FUNCTIONS: ReadonlySet<string> = new Set(NAMES);

export function unknownFunctions(calls: Iterable<string>): string[] {
  const found = new Set<string>();
  for (const name of calls) {
    if (!EXCEL_FUNCTIONS.has(name.toUpperCase())) found.add(name.toUpperCase());
  }
  return [...found].sort();
}
