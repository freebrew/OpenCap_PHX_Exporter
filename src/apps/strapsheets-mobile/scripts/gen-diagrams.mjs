// Reads apps-script/entry_diagrams.js and writes each tool drawing to public/diagrams/ plus
// src/diagrams.gen.ts (file, size, letter marks), so the phone shows the same drawings as
// Entry.html without a 250 KB inline module.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { runInNewContext } from "node:vm";

const source = readFileSync(new URL("../../../strapsheets/apps-script/entry_diagrams.js", import.meta.url), "utf8");
const scope = {};
runInNewContext(`${source}\n;this.out = { ENTRY_DIAGRAMS, ENTRY_DIAGRAM_MARKS, ENTRY_DIAGRAM_SIZES, ENTRY_DIAGRAM_LABEL_LETTERS };`, scope);
const { ENTRY_DIAGRAMS, ENTRY_DIAGRAM_MARKS, ENTRY_DIAGRAM_SIZES, ENTRY_DIAGRAM_LABEL_LETTERS } = scope.out;

const dir = new URL("../public/diagrams/", import.meta.url);
rmSync(dir, { recursive: true, force: true });
mkdirSync(dir, { recursive: true });

const diagrams = {};
for (const [which, dataUrl] of Object.entries(ENTRY_DIAGRAMS)) {
  const match = /^data:image\/(png|jpeg);base64,(.+)$/.exec(dataUrl);
  if (!match) throw new Error(`${which}: not a base64 image`);
  const file = `${which.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "")}.${match[1] === "jpeg" ? "jpg" : "png"}`;
  writeFileSync(new URL(file, dir), Buffer.from(match[2], "base64"));
  diagrams[which] = {
    file: `diagrams/${file}`,
    size: ENTRY_DIAGRAM_SIZES[which] ?? { w: 1280, h: 420 },
    marks: ENTRY_DIAGRAM_MARKS[which] ?? [],
    labelLetters: ENTRY_DIAGRAM_LABEL_LETTERS[which] ?? {},
  };
}

const out = `// GENERATED by scripts/gen-diagrams.mjs from apps-script/entry_diagrams.js. Do not edit.
import type { ToolDiagram } from "./diagramData";

export const TOOL_DIAGRAMS: Record<string, ToolDiagram> = ${JSON.stringify(diagrams, null, 2)};
`;
writeFileSync(new URL("../src/diagrams.gen.ts", import.meta.url), out);
for (const [which, diagram] of Object.entries(diagrams)) console.log(`  ${which}: ${diagram.file} ${diagram.size.w}x${diagram.size.h}, ${diagram.marks.length} marks`);
