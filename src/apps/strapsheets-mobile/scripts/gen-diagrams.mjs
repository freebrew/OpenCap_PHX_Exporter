// Reads the vector drawings and the sheet label map, then writes src/diagrams.gen.ts.
// The phone paints the SVG itself. The ring overlay stays in Diagram.tsx.
import { readFileSync, writeFileSync } from "node:fs";
import { runInNewContext } from "node:vm";

const vectors = new URL("../../../strapsheets/illustrations/vectors/", import.meta.url);
const source = readFileSync(new URL("../../../strapsheets/apps-script/entry_diagrams.js", import.meta.url), "utf8");
const scope = {};
runInNewContext(`${source}\n;this.out = { ENTRY_DIAGRAM_LABEL_LETTERS };`, scope);
const labels = scope.out.ENTRY_DIAGRAM_LABEL_LETTERS;
const tools = JSON.parse(readFileSync(new URL("drawlists.json", vectors), "utf8"));

function innerSvg(file) {
  const text = readFileSync(new URL(file, vectors), "utf8");
  const body = text.replace(/^<\?xml[^>]*>\s*/i, "").replace(/^<svg[^>]*>/i, "").replace(/<\/svg>\s*$/i, "");
  if (/<script|javascript:|on[a-z]+\s*=/i.test(body)) throw new Error(`${file} has active content`);
  return body;
}

const diagrams = {};
for (const tool of tools) {
  diagrams[tool.which] = {
    svg: innerSvg(`${tool.id}.svg`),
    size: { w: tool.w, h: tool.h },
    marks: tool.letters,
    labelLetters: labels[tool.which] ?? {},
  };
}

const out = `// GENERATED by scripts/gen-diagrams.mjs from illustrations/vectors. Do not edit.
import type { ToolDiagram } from "./diagramData";

export const TOOL_DIAGRAMS: Record<string, ToolDiagram> = ${JSON.stringify(diagrams, null, 2)};
`;
writeFileSync(new URL("../src/diagrams.gen.ts", import.meta.url), out);
for (const tool of tools) console.log(`  ${tool.which}: ${tool.w}x${tool.h}, ${tool.letters.length} marks`);
